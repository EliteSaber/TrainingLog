namespace TrainingLog.Tests;

/// <summary>
/// Группа тестов, трогающих WPF: окна, нити STA и общий для них render thread.
/// </summary>
/// <remarks>
/// WPF не любит, когда окна живут на разных STA-нитях одновременно: разбор окна при уходе
/// нити приходится на уже остановившийся диспетчер, и хост процесса падает нативно — тестовый
/// запуск прерывается целиком, а не падает один тест. Поэтому такие тесты выполняются
/// последовательно и отдельно от остальных: остальные (модели, правила, база) параллельностью
/// не падают и время на ней экономят.
/// </remarks>
[CollectionDefinition(Name, DisableParallelization = true)]
public sealed class WpfTestGroup
{
    /// <summary>Имя группы: тесты с этим атрибутом выполняются последовательно.</summary>
    public const string Name = "WPF";
}
