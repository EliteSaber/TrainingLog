using System.Windows.Controls;
using System.Windows.Input;

namespace TrainingLog.Controls;

/// <summary>
/// Скролл списка строк: берёт фокус себе, но нажатие до списка доводит.
/// </summary>
/// <remarks>
/// <see cref="ScrollViewer"/> помечает нажатие обработанным, когда забирает фокус себе
/// (<c>OnMouseLeftButtonDown</c>: <c>if (Focus()) e.Handled = true;</c>). Пока скролл стоял
/// <em>над</em> списком, это было безобидно: список был в маршруте нажатия раньше скролла, и
/// выделение строки менялось как прежде. Скролл внутри шаблона списка (так включают
/// виртуализацию, ловушка 30) стоит в маршруте <em>ниже</em> списка, и его «гашение» съедало
/// клик раньше списка: строка не выделялась ни кликом, ни повторным кликом (ловушка 31).
///
/// Здесь скролл возвращает нажатию прежний вид: помечено оно кнопкой строки — и такое
/// остаётся помеченным, — а фокус скролла больше не мешает. Фокус скроллу по-прежнему нужен:
/// на нём держится прокрутка страницами и стрелками, а список фокусируется отдельно.
/// </remarks>
public sealed class RowScrollViewer : ScrollViewer
{
    /// <summary>Забирает фокус и оставляет нажатие тем, чем оно было до фокуса.</summary>
    /// <remarks>
    /// Фокус скролла нужен для прокрутки, а его «гашение» нажатия — побочный эффект того же
    /// вызова, и от него список только мешает. Поэтому нажатие возвращается в прежнем виде:
    /// помеченным кнопкой строки оно и останется помеченным.
    /// </remarks>
    protected override void OnMouseLeftButtonDown(MouseButtonEventArgs e)
    {
        var handled = e.Handled;

        base.OnMouseLeftButtonDown(e);

        e.Handled = handled;
    }
}
