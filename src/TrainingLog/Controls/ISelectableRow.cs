namespace TrainingLog.Controls;

/// <summary>
/// Строка списка, признак выделения которой живёт на элементе данных, а не на контейнере.
/// </summary>
/// <remarks>
/// Панель с переработкой контейнеров отдаёт один контейнер разным строкам по очереди: признак,
/// оставленный на контейнере, пережил бы свою строку и подсветил бы чужую. Здесь признак едет
/// с элементом — контейнер, доставшийся по переработке чужой строке, читает признак её данных,
/// и подсветка всегда по адресу. Элементы без этого интерфейса живут в списках без переработки
/// и держат признак на контейнере, как раньше.
/// </remarks>
public interface ISelectableRow
{
    /// <summary>Выделена ли строка. Сеттер обязан поднять уведомление привязке подсветки.</summary>
    bool IsSelected { get; set; }
}
