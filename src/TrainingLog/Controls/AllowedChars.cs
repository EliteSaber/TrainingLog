namespace TrainingLog.Controls;

/// <summary>
/// Какие символы принимает поле ввода, помеченное поведением <see cref="AllowedCharsInput"/>.
/// </summary>
public enum AllowedChars
{
    /// <summary>
    /// Фильтр выключен, поле принимает любые символы. Значение по умолчанию: поведение
    /// включается только явным указанием набора, иначе фильтр висел бы на каждом поле окна.
    /// </summary>
    None = 0,

    /// <summary>
    /// Только цифры: количество повторений, количество показываемых дней.
    /// </summary>
    Digits,

    /// <summary>
    /// Цифры и десятичный разделитель — точка или запятая: вес подхода.
    /// </summary>
    /// <remarks>
    /// Оба разделителя разрешены по одной причине: в русской раскладке набирают запятую,
    /// а по привычке — точку, и <c>TryParse</c> умеет разобрать оба. Что именно набрано,
    /// решает уже разбор.
    /// </remarks>
    DigitsWithSeparators,
}
