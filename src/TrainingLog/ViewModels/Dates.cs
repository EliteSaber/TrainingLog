namespace TrainingLog.ViewModels;

/// <summary>Дата в виде, в котором она показывается в приложении: «08 октября 2026».</summary>
/// <remarks>
/// Собирается вручную, а не через <c>ToString</c> с шаблоном: по culture получается «8 октября
/// 2026 г.» — день без ведущего нуля, год сокращённым и с точкой, — и это ровно тот вид, который
/// здесь не нужен. Свой формат означает ещё и независимость от локали: <c>GetMonthName</c> на
/// немецкой машине вернул бы «Oktober», а месяцы здесь свои.
///
/// Одно место на оба применения — у строки журнала и у даты источника: два независимых формата
/// разъехались бы.
///
/// Имя класса не <c>DateText</c>: так называется свойство у строки журнала, и внутри своего же
/// класса имя члена перебивает имя типа — вызов <c>DateText.Format</c> собрался бы в
/// <c>string.Format</c> и упал бы на подписи.
/// </remarks>
public static class Dates
{
    /// <summary>
    /// Месяцы в родительном падеже и с маленькой буквы: «8 октября», «1 января».
    /// </summary>
    /// <remarks>
    /// Именительный дал бы «8 Октябрь». Формы родительного у месяцев свои, и «мая», «июня»,
    /// «июля» по аналогии не выводятся, поэтому список выписан целиком и проверяется на всех
    /// двенадцати.
    ///
    /// Индексируется <c>date.Month - 1</c>: <see cref="DateOnly.Month"/> нумеруется с единицы, а
    /// массив — с нуля.
    /// </remarks>
    private static readonly string[] MonthNames =
    [
        "января",
        "февраля",
        "марта",
        "апреля",
        "мая",
        "июня",
        "июля",
        "августа",
        "сентября",
        "октября",
        "ноября",
        "декабря",
    ];

    /// <summary>Дата в виде приложения: «08 октября 2026».</summary>
    /// <param name="date">Дата.</param>
    public static string Format(DateOnly date) =>
        $"{date.Day:00} {MonthNames[date.Month - 1]} {date.Year}";
}
