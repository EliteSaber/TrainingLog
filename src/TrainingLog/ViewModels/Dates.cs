namespace TrainingLog.ViewModels;

/// <summary>
/// Дата в виде, в котором она показывается в приложении: «08 октября 2026».
/// </summary>
/// <remarks>
/// Собирается вручную из трёх частей, а не через <c>ToString</c> с шаблоном, и это не
/// перестраховка. По culture получается «8 октября 2026 г.» — день без ведущего нуля, год
/// сокращённым и с точкой, — и это ровно тот вид, который в приложении не нужен. Свой
/// формат означает ещё и независимость от локали: <c>GetMonthName</c> на немецкой машине
/// вернул бы «Oktober», а названия месяцев у нас свои (см. <see cref="MonthNames"/>).
///
/// Одно место на оба применения — у строки журнала и у даты источника. Два независимых
/// формата разъехались бы, и это тот же класс ошибок, что и с форматом веса подхода.
///
/// Имя класса не `DateText`: так называется свойство у строки журнала, и внутри своего же
/// класса имя члена перебивает имя типа — вызов `DateText.Format` собрался бы в
/// <c>string.Format</c> и упал бы на подписи.
/// </remarks>
public static class Dates
{
    /// <summary>
    /// Месяцы в родительном падеже и с маленькой буквы: «8 октября», «1 января».
    /// </summary>
    /// <remarks>
    /// Именно в таком виде месяц пишется в дате по-русски: именительный падеж дал бы
    /// «8 Октябрь» — с большой буквы и не по-русски. Формы родительного у месяцев свои,
    /// и «мая», «июня», «июля» вставить по аналогии с остальными нельзя, поэтому список
    /// выписан целиком.
    ///
    /// Индексируется <c>date.Month - 1</c>: <see cref="DateOnly.Month"/> нумеруется с единицы,
    /// а массив — с нуля.
    /// </remarks>
    private static readonly string[] MonthNames =
    [
        "января",
        "февраля",
        "марта",
        "апреля",
        "мая",
        "июня",
        "июля",
        "августа",
        "сентября",
        "октября",
        "ноября",
        "декабря",
    ];

    /// <summary>
    /// Дата в виде приложения: «08 октября 2026».
    /// </summary>
    /// <param name="date">Дата.</param>
    public static string Format(DateOnly date) =>
        $"{date.Day:00} {MonthNames[date.Month - 1]} {date.Year}";
}