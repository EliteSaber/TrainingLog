using System.Threading.Tasks;
using TrainingLog.Core.Models;

namespace TrainingLog.Services;

/// <summary>Открытие и переключение между окнами приложения.</summary>
public interface IWindowService
{
    /// <summary>Справочник упражнений. Уже открытое окно выводится на передний план.</summary>
    void OpenExercises();

    /// <summary>Список планов. Уже открытое окно выводится на передний план.</summary>
    void OpenPlans();

    /// <summary>Показывает окно параметров, если окно дня закрыто; иначе выводит окно дня вперёд.</summary>
    /// <returns>
    /// <c>true</c>, если параметры приняты и записаны. <c>false</c> и когда окно отменено, и когда
    /// окно дня открыто — тогда оно уже выведено вперёд с оповещением, и открывать параметры
    /// поверх правящегося дня нельзя.
    /// </returns>
    bool ShowSettings();

    /// <returns><c>true</c>, если изменения приняты и сохранены.</returns>
    bool ShowEditExercise(Exercise exercise);

    /// <summary>
    /// Импорт упражнений из файла. Окно создаётся заново на каждый вызов, как и окно правки.
    /// </summary>
    /// <returns><c>true</c>, если упражнения записаны.</returns>
    bool ShowImportExercises();

    /// <summary>Добавление плана. Окно то же, что и при правке.</summary>
    /// <returns><c>true</c>, если план сохранён.</returns>
    bool ShowAddPlan();

    /// <returns><c>true</c>, если изменения приняты и сохранены.</returns>
    bool ShowEditPlan(TrainingPlan plan);

    /// <summary>
    /// Добавление дня. Немодальное окно: главное окно остаётся рабочим, на дату, по которой
    /// запись уже есть, откроется правка той же записи.
    /// </summary>
    /// <remarks>
    /// Повторный вызов не создаёт второе окно: уже открытое выводится на передний план с
    /// оповещением. О сохранении дня вызывающий узнаёт из <see cref="DaySaved"/> — результата
    /// «сохранилось и закрылось» здесь нет, окно может остаться открытым.
    /// </remarks>
    void ShowAddDay();

    /// <param name="day">
    /// Дата дня, который открывается на правку. Ответ тот же, что у добавления: при открытом окне
    /// дня попытка править другой день выводит существующее окно вперёд, не переключая дату.
    /// </param>
    void ShowEditDay(DateOnly day);

    /// <summary>Открытое окно дня записало день — журнал надо перечитать.</summary>
    /// <remarks>
    /// Задача подписчика возвращается вызовом события, чтобы перечитывание можно было дождаться
    /// await'ом в тесте. Подписчиков один, у окна дня нет «двух сохранений» по отдельности:
    /// и «Сохранить», и «Сохранить и закрыть» проходят через это же событие.
    /// </remarks>
    event Func<Task>? DaySaved;
}
