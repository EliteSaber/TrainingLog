using System.Threading.Tasks;
using TrainingLog.Core.Models;

namespace TrainingLog.Services;

/// <summary>Открытие и переключение между окнами приложения.</summary>
public interface IWindowService
{
    /// <summary>Справочник упражнений. Уже открытое окно выводится на передний план.</summary>
    void OpenExercises();

    /// <summary>Список планов. Уже открытое окно выводится на передний план.</summary>
    void OpenPlans();

    /// <summary>
    /// Окно параметров. Немодальное и единственное: открывается при любых открытых окнах,
    /// повторный вызов выводит уже открытое окно на передний план.
    /// </summary>
    /// <remarks>
    /// Результата у вызова нет: окно немодальное, и спрашивать у него «приняли ли» нечем —
    /// принять можно только записав файл. О записи вызывающий узнаёт из
    /// <see cref="SettingsSaved"/>.
    /// </remarks>
    void OpenSettings();

    /// <summary>Упражнение, которое сейчас правится; <c>null</c> — окна правки нет.</summary>
    /// <remarks>
    /// Источник истины — сервис: окно правки единственное, и при повторном открытии правится тот
    /// объект, который уже открыт, а не тот, по которому кликнули последним. Список использует
    /// это значение, чтобы не дать удалить редактируемую строку.
    /// </remarks>
    Exercise? EditedExercise { get; }

    /// <summary>План, который сейчас правится; <c>null</c> — окна правки нет.</summary>
    TrainingPlan? EditedPlan { get; }

    /// <summary>
    /// Окно правки упражнения. Отдельное и немодальное: справочник остаётся рабочим.
    /// </summary>
    /// <remarks>
    /// Ответа у вызова нет — окно немодальное, и «приняли ли» спрашивать нечем. О записи
    /// вызывающий узнаёт из <paramref name="onSaved"/>, о закрытии — из <paramref name="onClosed"/>:
    /// окно может закрыться и без записи, и список должен снять блокировку удаления.
    /// Обратные вызовы, а не события сервиса: подписчиком был бы временный
    /// <c>ExercisesViewModel</c>, а сервис — синглтон, и модель не покинула бы его никогда.
    /// </remarks>
    /// <param name="exercise">Упражнение, которое правится.</param>
    /// <param name="onSaved">Что делать, когда упражнение записано: перестроить видимый список.</param>
    /// <param name="onClosed">Что делать, когда окно правки закрылось.</param>
    void OpenEditExercise(Exercise exercise, Func<Task>? onSaved = null, Action? onClosed = null);

    /// <summary>Окно добавления плана. Отдельное и немодальное.</summary>
    /// <param name="onSaved">Что делать, когда план записан: перечитать планы.</param>
    /// <param name="onClosed">Что делать, когда окно плана закрылось.</param>
    void OpenAddPlan(Func<Task>? onSaved = null, Action? onClosed = null);

    /// <summary>Окно правки плана. Отдельное и немодальное.</summary>
    /// <param name="plan">План, который правится.</param>
    /// <param name="onSaved">Что делать, когда план записан: перечитать планы.</param>
    /// <param name="onClosed">Что делать, когда окно плана закрылось.</param>
    void OpenEditPlan(TrainingPlan plan, Func<Task>? onSaved = null, Action? onClosed = null);

    /// <summary>Окно импорта упражнений. Отдельное и немодальное.</summary>
    /// <param name="onSaved">Что делать, когда упражнения записаны: перечитать справочник.</param>
    /// <param name="onClosed">Что делать, когда окно импорта закрылось.</param>
    void OpenImportExercises(Func<Task>? onSaved = null, Action? onClosed = null);

    /// <summary>
    /// Добавление дня. Немодальное окно: главное окно остаётся рабочим, на дату, по которой
    /// запись уже есть, откроется правка той же записи.
    /// </summary>
    /// <remarks>
    /// Повторный вызов не создаёт второе окно: уже открытое выводится на передний план с
    /// оповещением. О сохранении дня вызывающий узнаёт из <see cref="DaySaved"/> — результата
    /// «сохранилось и закрылось» здесь нет, окно может остаться открытым.
    /// </remarks>
    void ShowAddDay();

    /// <param name="day">
    /// Дата дня, который открывается на правку. Ответ тот же, что у добавления: при открытом окне
    /// дня попытка править другой день выводит существующее окно вперёд, не переключая дату.
    /// </param>
    void ShowEditDay(DateOnly day);

    /// <summary>Открытое окно дня записало день — журнал надо перечитать.</summary>
    /// <remarks>
    /// Задача подписчика возвращается вызовом события, чтобы перечитывание можно было дождаться
    /// await'ом в тесте. Подписчиков один, у окна дня нет «двух сохранений» по отдельности:
    /// и «Сохранить», и «Сохранить и закрыть» проходят через это же событие.
    /// </remarks>
    event Func<Task>? DaySaved;

    /// <summary>Окно параметров записало настройки — главное окно обязано их перечитать.</summary>
    /// <remarks>
    /// Задача подписчика возвращается вызовом события, чтобы перечитывание можно было дождаться
    /// await'ом в тесте. Отличается от ответа диалога тем, что окно параметров немодальное:
    /// ответа «сохранилось и закрылось» у вызова нет, и событие — единственный способ узнать,
    /// что настройки записаны.
    /// </remarks>
    event Func<Task>? SettingsSaved;
}
