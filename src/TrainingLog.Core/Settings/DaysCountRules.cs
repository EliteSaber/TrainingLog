namespace TrainingLog.Core.Settings;

/// <summary>
/// Правила проверки количества показываемых дней. Общие для главного окна и окна параметров:
/// это одно и то же число, и две формы со своими пределами разошлись бы при первой правке.
/// </summary>
/// <remarks>
/// Отдельный класс, а не свойства у <see cref="AppSettings"/>, по той же причине, что
/// <c>NameRules</c> вынесен отдельно от наименований: правило проверки общее, а данные свои
/// у каждой сущности.
/// </remarks>
public static class DaysCountRules
{
    /// <summary>
    /// Меньше одного дня журнал не показывает: пустой список ничего не говорит, а кнопка
    /// «Добавить день» сбивает с толку — кажется, что записей нет.
    /// </summary>
    public const int MinDaysCount = 1;

    /// <summary>
    /// Больше дней показывать незачем: журнал показывают по одной записи в строке, и список
    /// длиннее года на экране всё равно не помещается.
    /// </summary>
    public const int MaxDaysCount = 366;

    /// <summary>
    /// Допустимо ли количество дней.
    /// </summary>
    /// <remarks>
    /// Проверка одна и та же для ввода в обоих окнах и для значения, прочитанного из файла
    /// настроек: правило не должно зависеть от того, откуда пришло число.
    /// </remarks>
    /// <param name="daysCount">Проверяемое количество дней.</param>
    public static bool IsValid(int daysCount) => daysCount is >= MinDaysCount and <= MaxDaysCount;
}
