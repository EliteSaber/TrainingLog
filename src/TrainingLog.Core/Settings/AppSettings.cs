namespace TrainingLog.Core.Settings;

/// <summary>
/// Настройки приложения — то, что записано в файле рядом с программой.
/// </summary>
/// <remarks>
/// Простой класс без поведения: файл читает и пишет <see cref="AppSettingsStore"/>, а
/// пригодность значения проверяет <see cref="DaysCountRules"/>. Своей проверки здесь
/// намеренно нет — иначе правило завелось бы в двух местах и разошлось бы с окнами.
/// </remarks>
public sealed class AppSettings
{
    /// <summary>
    /// Сколько дней показывать, пока пользователь ничего не выбрал.
    /// </summary>
    /// <remarks>
    /// Это же значение попадает в только что созданный файл настроек: приложение обязано
    /// создать его сразу, иначе пришлось бы держать в коде второе «умолчание» для случая
    /// «файла нет».
    /// </remarks>
    public const int DefaultDaysCount = 3;

    /// <summary>
    /// Сколько дней показывать в журнале.
    /// </summary>
    /// <remarks>
    /// Значение из файла может быть любым целым: файл правят руками. Пригодность проверяет
    /// хранилище при чтении, поэтому сюда попадает уже годное число.
    /// </remarks>
    public int DaysCount { get; set; } = DefaultDaysCount;
}
