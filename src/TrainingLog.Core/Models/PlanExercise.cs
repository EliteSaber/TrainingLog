namespace TrainingLog.Core.Models;

/// <summary>
/// Строка связи плана с упражнением: какое упражнение входит в план и на каком месте
/// в порядке выполнения.
/// </summary>
/// <remarks>
/// Связь many-to-many хранится теневой таблицей, но собственный класс у неё появился из-за
/// порядка: отсортировать <c>Include</c> по колонке теневой таблицы EF не умеет — у тени
/// нет навигации, по которой можно сортировать. С классом порядок выражается обычной
/// навигацией.
/// </remarks>
public sealed class PlanExercise
{
    /// <summary>Идентификатор плана. Часть составного ключа связи.</summary>
    public int TrainingPlanId { get; set; }

    /// <summary>Идентификатор упражнения. Часть составного ключа связи.</summary>
    public int ExerciseId { get; set; }

    /// <summary>
    /// Место упражнения в порядке выполнения плана. Считается с единицы и без пропусков.
    /// </summary>
    /// <remarks>
    /// С единицы — чтобы номер показывался в разметке без конвертера, то есть «+1» не нужно.
    /// </remarks>
    public int Order { get; set; }

    /// <summary>
    /// План, в состав которого входит упражнение.
    /// </summary>
    /// <remarks>
    /// Без инициализации: пустой <see cref="TrainingPlan"/> был бы несохранённым объектом,
    /// который EF попытался бы вставить вместе со связью. Обязательные навигации заполняются
    /// при добавлении связи явно.
    /// </remarks>
    public TrainingPlan Plan { get; set; } = null!;

    /// <summary>Упражнение из справочника. Заполняется при добавлении связи явно.</summary>
    public Exercise Exercise { get; set; } = null!;
}
